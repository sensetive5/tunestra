/** What the plan asks to put at a path in the project. */
export const OutputKind = {
  /** A file with the given content. */
  File: 'file',
  /** A copy of a source file, byte for byte. */
  Copy: 'copy',
  /** A relative symbolic link. */
  Symlink: 'symlink',
} as const;

export type OutputKind = (typeof OutputKind)[keyof typeof OutputKind];

/** First line of every generated markdown file; tunestra recognizes its files by it. */
export const GENERATED_MARKER = '<!-- Generated by tunestra';

export const GENERATED_NOTICE = `${GENERATED_MARKER}. Do not edit: change the sources and run \`tunestra setup\`. -->`;

/** Shared output that any agent can read. */
export const AGENTS_DIR = '.agents';

/** Rules for every agent, ordered from specific to general by their file names. */
export const AGENTS_RULES_DIR = `${AGENTS_DIR}/rules`;

/** Skills in the Agent Skills layout that several agents read. */
export const AGENTS_SKILLS_DIR = `${AGENTS_DIR}/skills`;

/** What tunestra generated last time. */
export const STATE_DIR = '.tunestra/state';

export const GITIGNORE_FILE = '.gitignore';

/** The registry of outputs from the last setup. */
export const STATE_FILE = `${STATE_DIR}/outputs.json`;

/** Bump when the shape of the state file changes. */
export const STATE_VERSION = 1;
