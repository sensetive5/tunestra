import { parse } from 'smol-toml';
import { describe, expect, it } from 'vitest';
import type { McpConfig, McpServer } from '../../../shared/types/preset.ts';
import type { Origin, ResolvedArtifact } from '../../../shared/types/resolution.ts';
import { renderConfigToml } from '../config-toml.ts';

const BASE: Origin = {
  name: 'base',
  level: 'base',
  dir: '/presets/base',
  artifactsDir: '/presets/base',
  remote: undefined,
};

function createServer(key: string, config: McpConfig): ResolvedArtifact<McpServer> {
  const source = `mcp/${key}.yaml`;

  return {
    artifact: {
      key,
      source,
      description: undefined,
      config,
    },
    origin: BASE,
    overrides: [],
    patchedBy: [],
  };
}

describe('renderConfigToml', () => {
  it('writes the rules as a literal string that people can read', () => {
    const instructions = '# Rules\n\nUse "double" quotes and C:\\paths.\n';

    const toml = renderConfigToml({
      instructions: instructions,
      servers: [],
      env: [],
    });

    const config = parse(toml);
    expect(toml).toContain("developer_instructions = '''\n# Rules\n");
    expect(config.developer_instructions).toBe(instructions);
  });

  it('escapes the rules when they contain three single quotes', () => {
    const instructions = "Write '''text''' like this.\n";

    const toml = renderConfigToml({
      instructions: instructions,
      servers: [],
      env: [],
    });

    const config = parse(toml);
    expect(toml).toContain('developer_instructions = "Write');
    expect(config.developer_instructions).toBe(instructions);
  });

  it('escapes the rules when they contain a control character', () => {
    const instructions = 'Line one\r\nLine two\u001B\n';

    const toml = renderConfigToml({
      instructions: instructions,
      servers: [],
      env: [],
    });

    const config = parse(toml);
    expect(config.developer_instructions).toBe(instructions);
  });

  it('writes MCP servers in the shape Codex reads', () => {
    const local = createServer('memory', {
      command: 'npx',
      args: ['-y', 'memory'],
      env: {
        MEMORY_FILE: 'memory.json',
      },
    });
    const remote = createServer('docs', {
      type: 'http',
      url: 'https://docs.example.com/mcp',
      headers: {
        'X-Team': 'frontend',
      },
    });

    const toml = renderConfigToml({
      instructions: undefined,
      servers: [local, remote],
      env: [],
    });

    const config = parse(toml);
    expect(config).toEqual({
      mcp_servers: {
        memory: {
          command: 'npx',
          args: ['-y', 'memory'],
          env: {
            MEMORY_FILE: 'memory.json',
          },
        },
        docs: {
          url: 'https://docs.example.com/mcp',
          http_headers: {
            'X-Team': 'frontend',
          },
        },
      },
    });
  });

  it('gives the variables to the commands that Codex runs, sorted by name', () => {
    const variables = ['MCP_TIMEOUT', 'API_URL'].map((key) => ({
      artifact: {
        key,
        source: 'tunestra.preset.yaml',
        value: key.toLowerCase(),
      },
      origin: BASE,
      overrides: [],
      patchedBy: [],
    }));

    const toml = renderConfigToml({
      instructions: undefined,
      servers: [],
      env: variables,
    });

    expect(toml).toContain(
      '[shell_environment_policy.set]\nAPI_URL = "api_url"\nMCP_TIMEOUT = "mcp_timeout"\n',
    );
  });

  it('starts with the marker of generated files', () => {
    const toml = renderConfigToml({
      instructions: 'Rules.\n',
      servers: [],
      env: [],
    });

    expect(toml.startsWith('# Generated by tunestra')).toBe(true);
  });
});
