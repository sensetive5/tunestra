import { PROJECT_CONFIG } from '../shared/constants/files.ts';
import { AGENTS_RULES_DIR, AGENTS_SKILLS_DIR } from '../shared/constants/output.ts';
import type { Chain } from '../shared/types/chain.ts';
import type { Command, McpServer, Preset, Rule, Skill } from '../shared/types/preset.ts';
import type { ResolvedArtifact } from '../shared/types/resolution.ts';
import { renderTable } from '../shared/utils/markdown.ts';
import { relativePosix } from '../shared/utils/paths.ts';
import { describeOrigin } from './describe-origin.ts';
import { buildRuleFileName } from './rule-file.ts';

const HIERARCHY_INTRO =
  'Instructions are ordered from specific to general. When two instructions conflict, follow the one from the higher level in this list.';

const RULES_INTRO =
  'Always follow these rules. Claude Code loads them automatically; other agents should read them before starting work.';

const SKILLS_INTRO = 'Use a skill when the task matches its description.';

export const CHANGING_SECTION = [
  '## Changing this setup',
  '',
  'Do not edit this file or the generated directories. Edit the sources (`tunestra.yaml`, `.tunestra/` or the presets above) and run `tunestra setup`.',
].join('\n');

export function renderHierarchy(chain: Chain): string {
  const specificFirst = chain.levels.toReversed();
  const rows = specificFirst.map((level, index) => {
    const number = String(index + 1);
    const source = describeLevelSource(chain, level);

    return [number, level.level, level.name, source];
  });
  const table = renderTable(['#', 'Level', 'Preset', 'Source'], rows);

  return renderSection('Hierarchy', HIERARCHY_INTRO, table);
}

export function renderRules(rules: ReadonlyArray<ResolvedArtifact<Rule>>): string {
  const rows = rules.map((rule) => {
    const origin = describeOrigin(rule);
    const description = rule.artifact.description ?? '';
    const fileName = buildRuleFileName(rule);

    return [rule.artifact.key, origin, description, `${AGENTS_RULES_DIR}/${fileName}`];
  });
  const table = renderTable(['Rule', 'Level', 'Description', 'File'], rows);

  return renderSection('Rules', RULES_INTRO, table);
}

export function renderSkills(skills: ReadonlyArray<ResolvedArtifact<Skill>>): string {
  const rows = skills.map((skill) => {
    const origin = describeOrigin(skill);
    const file = `${AGENTS_SKILLS_DIR}/${skill.artifact.key}/SKILL.md`;

    return [skill.artifact.key, origin, skill.artifact.description, file];
  });
  const table = renderTable(['Skill', 'Level', 'When to use', 'File'], rows);

  return renderSection('Skills', SKILLS_INTRO, table);
}

export function renderCommands(commands: ReadonlyArray<ResolvedArtifact<Command>>): string {
  const rows = commands.map((command) => {
    const origin = describeOrigin(command);
    const description = command.artifact.description ?? '';

    return [`/${command.artifact.key}`, origin, description];
  });
  const table = renderTable(['Command', 'Level', 'Description'], rows);

  return renderSection('Commands', undefined, table);
}

export function renderMcpServers(servers: ReadonlyArray<ResolvedArtifact<McpServer>>): string {
  const rows = servers.map((server) => {
    const origin = describeOrigin(server);
    const description = server.artifact.description ?? '';

    return [server.artifact.key, origin, description];
  });
  const table = renderTable(['Server', 'Level', 'Description'], rows);

  return renderSection('MCP servers', undefined, table);
}

/** The project shows its config file; a preset shows its path from the project. */
function describeLevelSource(chain: Chain, level: Preset): string {
  const isProject = level.dir === chain.project.dir;

  if (isProject) {
    return PROJECT_CONFIG;
  }

  return relativePosix(chain.project.dir, level.dir);
}

function renderSection(title: string, intro: string | undefined, table: string): string {
  const heading = `## ${title}`;

  if (intro === undefined) {
    return [heading, '', table].join('\n');
  }

  return [heading, '', intro, '', table].join('\n');
}
