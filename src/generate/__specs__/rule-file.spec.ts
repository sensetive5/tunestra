import { describe, expect, it } from 'vitest';
import type { Rule } from '../../shared/types/preset.ts';
import type { Origin, ResolvedArtifact } from '../../shared/types/resolution.ts';
import { buildRuleFileName, renderRuleFile } from '../rule-file.ts';

const TEAM: Origin = {
  name: 'team',
  level: 'team',
  dir: '/presets/team',
  artifactsDir: '/presets/team',
};

const BASE: Origin = {
  name: 'base',
  level: 'base',
  dir: '/presets/base',
  artifactsDir: '/presets/base',
};

function createRule(
  key: string,
  origin: Origin,
  overrides: ReadonlyArray<Origin>,
): ResolvedArtifact<Rule> {
  const source = `rules/${key}.md`;

  return {
    artifact: {
      key,
      source,
      description: undefined,
      body: '# Text\n',
    },
    origin,
    overrides,
    patchedBy: [],
  };
}

describe('buildRuleFileName', () => {
  it('starts with the rank and the level', () => {
    const rule = createRule('code-style', TEAM, []);

    const fileName = buildRuleFileName(rule);

    expect(fileName).toBe('20-team-code-style.md');
  });

  it('names level instructions after the level', () => {
    const rule = createRule('instructions@team', TEAM, []);

    const fileName = buildRuleFileName(rule);

    expect(fileName).toBe('20-team-instructions.md');
  });

  it('adds the preset name when it differs from the level', () => {
    const frontend: Origin = {
      ...TEAM,
      name: 'frontend',
    };
    const rule = createRule('instructions@frontend', frontend, []);

    const fileName = buildRuleFileName(rule);

    expect(fileName).toBe('20-team-instructions-frontend.md');
  });
});

describe('renderRuleFile', () => {
  it('starts with the origin and the overridden levels', () => {
    const rule = createRule('code-style', TEAM, [BASE]);

    const content = renderRuleFile(rule);

    expect(content).toBe(
      [
        '<!-- Generated by tunestra from team:rules/code-style.md. Do not edit. -->',
        '> Level: team, preset: team. Overrides: base.',
        '',
        '# Text',
        '',
      ].join('\n'),
    );
  });
});
