import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { createTempDir, createTree } from '../../shared/tests/temp.ts';
import { readLock } from '../read-lock.ts';
import { renderLock } from '../render-lock.ts';

const COMMIT = 'c9f077f0be2838d45cf7592f1f57615810b3973c';

describe('readLock', () => {
  it('reads what renderLock wrote, with the sources sorted', async () => {
    const sources = {
      'gitlab:org/b#main': {
        commit: COMMIT,
        integrity: 'sha256-b',
      },
      'github:org/a#v1': {
        commit: COMMIT,
        integrity: 'sha256-a',
      },
      'github:org/c#v1': {
        commit: COMMIT,
        integrity: 'sha256-c',
      },
    };
    const content = renderLock(sources);
    const root = await createTree({
      'tunestra.lock.yaml': content,
    });

    const lock = await readLock(root);

    const keys = Object.keys(lock);
    expect(lock).toEqual(sources);
    expect(keys).toEqual(['github:org/a#v1', 'github:org/c#v1', 'gitlab:org/b#main']);
    expect(content).toMatch(/^# Generated by tunestra/);
  });

  it('has no sources without the file', async () => {
    const root = await createTempDir('project');

    const lock = await readLock(root);

    expect(lock).toEqual({});
  });

  it('rejects a short commit', async () => {
    const root = await createTree({
      'tunestra.lock.yaml':
        'version: 1\nsources:\n  github:org/a#v1:\n    commit: c9f077f\n    integrity: sha256-a\n',
    });
    const file = join(root, 'tunestra.lock.yaml');

    const result = readLock(root);

    await expect(result).rejects.toThrow(`Invalid lock file ${file}`);
  });
});
